const dictionaries: Record<Locale, Dictionary> = { en, es }

type I18nValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string, vars?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const locale = useUI((s) => s.locale)
  const setLocale = useUI((s) => s.setLocale)

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      const raw = dictionaries[locale][key] ?? en[key] ?? key
      if (!vars) return raw
      return Object.entries(vars).reduce((acc, [k, v]) => acc.replace(`{${k}}`, String(v)), raw)
    },
    [locale],
  )

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}

export function categoryLabel(category: string, categories: { key: string; labelEn: string; labelEs: string }[], locale: Locale) {
  const match = categories.find((c) => c.key === category)
  if (!match) return category.replace(/_/g, ' ')
  return locale === 'es' ? match.labelEs : match.labelEn
}
